#!/usr/bin/env python3
"""Stand-in data so Carthage's screens open in a visual QML editor (Qt Creator's Design
mode / Qt Design Studio) and in the `qml` previewer.

Every screen asks the Python engine (the `Backend` singleton, `import Carthage`) for its
colors, sizes and games; an editor doesn't run Python, so without this the screens come up
blank. qml/carthage.qmlproject adds qml/designer/ to the import path, where a stand-in
`Carthage` module provides a QML `Backend` singleton. This script writes that singleton
from the real theme, settings and demo library, so re-run it after changing theme.py or
settings.py:

    python tools/make_designer_data.py

What still doesn't show in an editor: pictures painted by Python (the plastic shells,
pockets, shadows, icons: image://gc/…) and the 3D card. Layout, text, colors and every
control do.
"""

