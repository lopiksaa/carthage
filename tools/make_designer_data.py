from carthage.library import SOURCES, fake_games  # noqa: E402
from carthage.settings import Settings  # noqa: E402
from carthage.version import VERSION  # noqa: E402

OUT = ROOT / "carthage" / "qml" / "designer" / "Carthage" / "Backend.qml"


def js(value):
    """A value as QML/JavaScript. Objects get parentheses: after a colon, a bare {…} would
    read as a code block."""
    text = json.dumps(value, ensure_ascii=False)
    return f"({text})" if isinstance(value, dict) else text


